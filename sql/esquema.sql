CREATE TABLE PESSOA (
    CPF_CNPJ VARCHAR2(14) NOT NULL,
    NOME VARCHAR2(60) NOT NULL,
    TELEFONE VARCHAR2(11) NOT NULL,
    EMAIL VARCHAR2(30),
    SENHA VARCHAR2(8) NOT NULL,
    CONSTRAINT PK_PESSOA PRIMARY KEY (CPF_CNPJ)
);

CREATE TABLE FUNCAO (
    -- Inserções nessa tabela serão feitas "manualmente", sem uso de triggers,
    -- quando se cadastram novas tuplas para "Pessoa" com suas respectivas funções
    CPF_CNPJ VARCHAR2(14) NOT NULL,
    FUNCAO_PESSOA VARCHAR2(60) NOT NULL,
    CONSTRAINT PK_FUNCAO PRIMARY KEY (CPF_CNPJ, FUNCAO_PESSOA)
);

CREATE TABLE PROPRIETARIO (
    CPF_CNPJ VARCHAR2(14) NOT NULL,
    TIPO VARCHAR2(20) NOT NULL,
    PERCENTUAL_POSSE NUMBER(5,2) NOT NULL, -- Até 5 dígitos com 2 casas decimais
    CONSTRAINT PK_PROPRIETARIO PRIMARY KEY (CPF_CNPJ),
    CONSTRAINT FK_PROPRIETARIO_PESSOA FOREIGN KEY (CPF_CNPJ) REFERENCES PESSOA(CPF_CNPJ) 
);

CREATE TABLE SUPERVISOR (
    CPF_CNPJ VARCHAR2(14) NOT NULL,
    REGISTRO_PROFISSIONAL VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_SUPERVISOR PRIMARY KEY (CPF_CNPJ),
    CONSTRAINT FK_SUPERVISOR_PESSOA FOREIGN KEY (CPF_CNPJ) REFERENCES PESSOA(CPF_CNPJ) 
);

CREATE TABLE CLIENTE (
    CPF_CNPJ VARCHAR2(14) NOT NULL,
    DATA_CADASTRO DATE NOT NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (CPF_CNPJ),
    CONSTRAINT FK_CLIENTE_PESSOA FOREIGN KEY (CPF_CNPJ) REFERENCES PESSOA(CPF_CNPJ) 
);

CREATE TABLE FUNCIONARIO (
    CPF_CNPJ VARCHAR2(14) NOT NULL,
    DATA_ADMISSAO DATE NOT NULL,
    TURNO VARCHAR2(20) NOT NULL,
    SALARIO NUMBER(10,2),
    STATUS VARCHAR2(15),
    EH_AGRICULTOR CHAR(1) NOT NULL CHECK (EH_AGRICULTOR IN ('S', 'N')),
    ESPECIALIDADE_AGRICOLA VARCHAR2(20),  -- Não pode ser not null pois se for operador, esse campo será nulo
    EH_OPERADOR CHAR(1) NOT NULL CHECK (EH_OPERADOR IN ('S', 'N')),
    TIPO VARCHAR2(50), -- Não pode ser not null pois se for agricultor, esse campo será nulo
    QUALIFICACAO VARCHAR2(50),  -- Não pode ser not null pois se for agricultor, esse campo será nulo
    CONSTRAINT PK_FUNCIONARIO PRIMARY KEY (CPF_CNPJ),
    CONSTRAINT FK_FUNCIONARIO_PESSOA FOREIGN KEY (CPF_CNPJ) REFERENCES PESSOA(CPF_CNPJ) 
);

CREATE TABLE PROPRIEDADE_RURAL (
    COD_IMOVEL_RURAL NUMBER(13) NOT NULL,
    NOME VARCHAR2(30) NOT NULL,
    CEP CHAR(8) NOT NULL,
    NUMERO NUMBER(4) NOT NULL,
    LOGRADOURO VARCHAR2(50) NOT NULL,
    CIDADE VARCHAR2(15) NOT NULL,
    ESTADO VARCHAR2(15) NOT NULL,
    PAIS VARCHAR2(15) NOT NULL,
    AREA_TOTAL NUMBER(10,2) NOT NULL,
    CONSTRAINT PK_PROPRIEDADE_RURAL PRIMARY KEY (COD_IMOVEL_RURAL)
);

CREATE TABLE POSSUI (
    PROPRIETARIO VARCHAR2(14) NOT NULL,
    COD_IMOVEL_RURAL NUMBER(13) NOT NULL,
    CONSTRAINT PK_POSSUI PRIMARY KEY (COD_IMOVEL_RURAL, PROPRIETARIO),
    CONSTRAINT FK_POSSUI_PROPRIEDADE_RURAL FOREIGN KEY (COD_IMOVEL_RURAL) REFERENCES PROPRIEDADE_RURAL(COD_IMOVEL_RURAL),
    CONSTRAINT FK_POSSUI_PROPRIETARIO FOREIGN KEY (PROPRIETARIO) REFERENCES PROPRIETARIO(CPF_CNPJ)  
); 

CREATE TABLE LOTE_PLANTIO (
    COD_IMOVEL_RURAL NUMBER(13) NOT NULL,
    NUMERO NUMBER(4) NOT NULL,
    STATUS VARCHAR2(15) NOT NULL,
    AREA_TOTAL NUMBER(10,2) NOT NULL,
    CULTURA VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_LOTE_PLANTIO PRIMARY KEY (COD_IMOVEL_RURAL, NUMERO),
    CONSTRAINT FK_LOTE_PLANTIO_PROPRIEDADE_RURAL FOREIGN KEY (COD_IMOVEL_RURAL) REFERENCES PROPRIEDADE_RURAL(COD_IMOVEL_RURAL),
    CONSTRAINT CK_LOTE_STATUS
        CHECK (STATUS IN ('LIVRE', 'OCUPADO', 'EM PREPARO'))
);

CREATE TABLE SAFRA (
    ID_SAFRA NUMBER(10) GENERATED ALWAYS AS IDENTITY, -- Id artificial sequencial
    COD_IMOVEL_RURAL NUMBER(13) NOT NULL,
    NUM_LOTE NUMBER(4) NOT NULL,
    DATA_HORA_PLANTIO DATE NOT NULL,
    DATA_HORA_COLHEITA DATE,
    QUANTIDADE NUMBER(10,2),
    CONSTRAINT PK_SAFRA PRIMARY KEY (ID_SAFRA),
    CONSTRAINT FK_SAFRA_LOTE_PLANTIO FOREIGN KEY (COD_IMOVEL_RURAL, NUM_LOTE) REFERENCES LOTE_PLANTIO(COD_IMOVEL_RURAL, NUMERO),
    CONSTRAINT UQ_SAFRA UNIQUE (COD_IMOVEL_RURAL, NUM_LOTE, DATA_HORA_PLANTIO),
    CONSTRAINT CK_SAFRA_DATAS
        CHECK (
            DATA_HORA_COLHEITA IS NULL
            OR DATA_HORA_PLANTIO < DATA_HORA_COLHEITA
        )
);

CREATE TABLE CONSULTA (
    ID_SAFRA NUMBER(10) NOT NULL,
    CPF_CNPJ_CLIENTE VARCHAR2(14) NOT NULL,
    DATA_HORA_CONSULTA DATE NOT NULL,
    CONSTRAINT PK_CONSULTA PRIMARY KEY (ID_SAFRA, CPF_CNPJ_CLIENTE, DATA_HORA_CONSULTA),
    CONSTRAINT FK_CONSULTA_SAFRA FOREIGN KEY (ID_SAFRA) REFERENCES SAFRA(ID_SAFRA),
    CONSTRAINT FK_CONSULTA_CLIENTE FOREIGN KEY (CPF_CNPJ_CLIENTE) REFERENCES CLIENTE(CPF_CNPJ)
);

CREATE TABLE ATIVIDADE_AGRICOLA (
    ID_ATIVIDADE NUMBER(10) GENERATED ALWAYS AS IDENTITY, -- Id artificial sequencial,
    COD_IMOVEL_RURAL NUMBER(13) NOT NULL,
    NUM_LOTE NUMBER(4) NOT NULL,
    DATA_HORA_INICIO DATE NOT NULL,
    DATA_HORA_FIM DATE,
    DURACAO NUMBER(10,2),
    AREA_TRABALHADA NUMBER(10,2),
    TEMPO_USO_MAQUINAS NUMBER(10,2),
    TIPO_ATIVIDADE VARCHAR2(20) NOT NULL,
    EMISSAO_CO2 NUMBER(10,2),
    COD_BARRAS_INSUMO VARCHAR2(20),
    CONSTRAINT PK_ATIVIDADE_AGRICOLA PRIMARY KEY (ID_ATIVIDADE),
    CONSTRAINT UQ_ATIVIDADE_AGRICOLA UNIQUE (COD_IMOVEL_RURAL, NUM_LOTE, DATA_HORA_INICIO),
    CONSTRAINT FK_ATIVIDADE_AGRICOLA_LOTE_PLANTIO FOREIGN KEY (COD_IMOVEL_RURAL, NUM_LOTE) REFERENCES LOTE_PLANTIO(COD_IMOVEL_RURAL, NUMERO),
    CONSTRAINT CK_ATIVIDADE_DATAS
        CHECK (
            DATA_HORA_FIM IS NULL
            OR DATA_HORA_INICIO < DATA_HORA_FIM
        )
);

CREATE TABLE REALIZADA_POR (
    ID_ATIVIDADE NUMBER(10) NOT NULL,
    CPF_CNPJ_FUNC VARCHAR2(14) NOT NULL,
    CONSTRAINT PK_REALIZADA_POR PRIMARY KEY (ID_ATIVIDADE, CPF_CNPJ_FUNC),
    CONSTRAINT FK_REALIZADA_POR_ATIVIDADE_AGRICOLA FOREIGN KEY (ID_ATIVIDADE) REFERENCES ATIVIDADE_AGRICOLA(ID_ATIVIDADE),
    CONSTRAINT FK_REALIZADA_POR_FUNCIONARIO FOREIGN KEY (CPF_CNPJ_FUNC) REFERENCES FUNCIONARIO(CPF_CNPJ)
);

CREATE TABLE VALIDACAO (
    ID_ATIVIDADE NUMBER(10) NOT NULL,
    CPF_CNPJ_SUPERVISOR VARCHAR2(14) NOT NULL,
    DATA_HORA DATE NOT NULL,
    STATUS VARCHAR2(15) NOT NULL,
    CONSTRAINT PK_VALIDACAO PRIMARY KEY (ID_ATIVIDADE, CPF_CNPJ_SUPERVISOR, DATA_HORA),
    CONSTRAINT FK_VALIDACAO_ATIVIDADE_AGRICOLA FOREIGN KEY (ID_ATIVIDADE) REFERENCES ATIVIDADE_AGRICOLA(ID_ATIVIDADE),
    CONSTRAINT FK_VALIDACAO_SUPERVISOR FOREIGN KEY (CPF_CNPJ_SUPERVISOR) REFERENCES SUPERVISOR(CPF_CNPJ),
    CONSTRAINT CK_VALIDACAO_STATUS
        CHECK (STATUS IN ('APROVADO', 'REJEITADO'))
);

