CREATE TABLE INSUMO (
    COD_BARRAS VARCHAR2(20) NOT NULL,
    TIPO VARCHAR2(20) NOT NULL,
    NOME VARCHAR2(30) NOT NULL,
    MARCA VARCHAR2(20) NOT NULL,
    VALIDADE DATE NOT NULL,
    FABRICANTE VARCHAR2(30) NOT NULL,
    CONSTRAINT PK_INSUMO PRIMARY KEY (COD_BARRAS)
);

CREATE TABLE AGROTOXICO (
    COD_BARRAS VARCHAR2(20) NOT NULL,
    CLASSE_TOXICOLOGICA VARCHAR2(50),
    TEMPO_CARENCIA NUMBER,
    CONSTRAINT PK_AGROTOXICO PRIMARY KEY (COD_BARRAS),
    CONSTRAINT FK_AGROTOXICO_INSUMO 
        FOREIGN KEY (COD_BARRAS) REFERENCES INSUMO(COD_BARRAS),
    CONSTRAINT CK_AGROTOXICO_CLASSE
        CHECK (CLASSE_TOXICOLOGICA IN (
            'CLASSE I', -- Pouco tóxico
            'CLASSE II', -- Medianamente tóxico
            'CLASSE III' -- Altamente tóxico
            ))
);

CREATE TABLE LISTADO_EM (
    COD_BARRAS_AGROTOXICO VARCHAR2(20) NOT NULL,
    CNPJ_PONTO_COLETA CHAR(14) NOT NULL,
    DATA_DESCARTE DATE NOT NULL,
    CONSTRAINT PK_LISTADO_EM PRIMARY KEY (COD_BARRAS_AGROTOXICO, CNPJ_PONTO_COLETA, DATA_DESCARTE),
    CONSTRAINT FK_LISTADO_EM_AGROTOXICO 
        FOREIGN KEY (COD_BARRAS_AGROTOXICO) 
        REFERENCES AGROTOXICO(COD_BARRAS),
    CONSTRAINT FK_LISTADO_EM_COMPROVANTE 
        FOREIGN KEY (CNPJ_PONTO_COLETA, DATA_DESCARTE)
        REFERENCES COMPROVANTE_DESCARTE(CNPJ_PONTO_COLETA, DATA_DESCARTE)
);

